import type { OpenAPIDocument, OperationObject, ParameterObject, SchemaObject } from "./types.js";
import { HTTP_METHODS } from "./types.js";
import { refName, schemaToZod } from "./zod.js";

interface Operation {
  name: string;
  method: string;
  path: string;
  summary?: string;
  pathParams: ParameterObject[];
  queryParams: ParameterObject[];
  body?: SchemaObject;
  bodyRequired: boolean;
  response?: SchemaObject;
}

/** Generate a single-file TypeScript SDK from an OpenAPI document. */
export function generate(doc: OpenAPIDocument): string {
  const out: string[] = [];
  out.push(`// Generated by ts-sdk-generator from "${doc.info.title}" v${doc.info.version}. Do not edit.`);
  out.push(`import { z } from "zod";`, "");

  out.push(...generateSchemas(doc));
  out.push(...generateClient(doc, collectOperations(doc)));
  return out.join("\n") + "\n";
}

function generateSchemas(doc: OpenAPIDocument): string[] {
  const schemas = doc.components?.schemas ?? {};
  const lines: string[] = [];
  for (const [name, schema] of orderByDependencies(schemas)) {
    const id = refName(name);
    lines.push(`export const ${id}Schema = ${schemaToZod(schema)};`);
    lines.push(`export type ${id} = z.infer<typeof ${id}Schema>;`, "");
  }
  return lines;
}

/** Topologically sort component schemas so referenced schemas are declared first. */
function orderByDependencies(schemas: Record<string, SchemaObject>): [string, SchemaObject][] {
  const result: [string, SchemaObject][] = [];
  const visited = new Set<string>();
  const visit = (name: string) => {
    if (visited.has(name) || !schemas[name]) return;
    visited.add(name);
    for (const dep of collectRefs(schemas[name])) visit(dep);
    result.push([name, schemas[name]]);
  };
  Object.keys(schemas).forEach(visit);
  return result;
}

function collectRefs(schema: SchemaObject | undefined, acc: string[] = []): string[] {
  if (!schema) return acc;
  if (schema.$ref) acc.push(schema.$ref.split("/").pop()!);
  collectRefs(schema.items, acc);
  Object.values(schema.properties ?? {}).forEach((s) => collectRefs(s, acc));
  [...(schema.oneOf ?? []), ...(schema.anyOf ?? []), ...(schema.allOf ?? [])].forEach((s) => collectRefs(s, acc));
  if (typeof schema.additionalProperties === "object") collectRefs(schema.additionalProperties, acc);
  return acc;
}

function collectOperations(doc: OpenAPIDocument): Operation[] {
  const ops: Operation[] = [];
  for (const [path, item] of Object.entries(doc.paths)) {
    for (const method of HTTP_METHODS) {
      const op = item[method];
      if (!op) continue;
      const params = [...(item.parameters ?? []), ...(op.parameters ?? [])];
      ops.push({
        name: op.operationId ?? fallbackName(method, path),
        method: method.toUpperCase(),
        path,
        summary: op.summary,
        pathParams: params.filter((p) => p.in === "path"),
        queryParams: params.filter((p) => p.in === "query"),
        body: op.requestBody?.content?.["application/json"]?.schema,
        bodyRequired: op.requestBody?.required ?? false,
        response: successSchema(op),
      });
    }
  }
  return ops;
}

function successSchema(op: OperationObject): SchemaObject | undefined {
  const code = Object.keys(op.responses ?? {}).find((c) => c.startsWith("2"));
  return code ? op.responses![code].content?.["application/json"]?.schema : undefined;
}

function fallbackName(method: string, path: string): string {
  const parts = path
    .split("/")
    .filter(Boolean)
    .map((p) => (p.startsWith("{") ? "By" + cap(p.slice(1, -1)) : cap(p)));
  return method + parts.join("").replace(/[^a-zA-Z0-9]/g, "");
}

const cap = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);

function generateClient(doc: OpenAPIDocument, ops: Operation[]): string[] {
  const baseUrl = doc.servers?.[0]?.url ?? "";
  const lines: string[] = [
    `export interface ClientOptions {`,
    `  baseUrl?: string;`,
    `  headers?: Record<string, string>;`,
    `  fetch?: typeof fetch;`,
    `}`,
    "",
    `export class ApiError extends Error {`,
    `  constructor(public status: number, public body: unknown) {`,
    `    super(\`Request failed with status \${status}\`);`,
    `  }`,
    `}`,
    "",
    `export class ApiClient {`,
    `  private baseUrl: string;`,
    `  private headers: Record<string, string>;`,
    `  private fetchFn: typeof fetch;`,
    "",
    `  constructor(options: ClientOptions = {}) {`,
    `    this.baseUrl = options.baseUrl ?? ${JSON.stringify(baseUrl)};`,
    `    this.headers = options.headers ?? {};`,
    `    this.fetchFn = options.fetch ?? globalThis.fetch.bind(globalThis);`,
    `  }`,
    "",
    `  private async request<T>(`,
    `    method: string,`,
    `    path: string,`,
    `    schema: z.ZodType<T>,`,
    `    query?: Record<string, unknown>,`,
    `    body?: unknown,`,
    `  ): Promise<T> {`,
    `    const url = new URL(this.baseUrl + path);`,
    `    for (const [k, v] of Object.entries(query ?? {})) {`,
    `      if (v !== undefined) url.searchParams.set(k, String(v));`,
    `    }`,
    `    const res = await this.fetchFn(url, {`,
    `      method,`,
    `      headers: { ...(body !== undefined ? { "Content-Type": "application/json" } : {}), ...this.headers },`,
    `      body: body !== undefined ? JSON.stringify(body) : undefined,`,
    `    });`,
    `    const text = await res.text();`,
    `    const data = text ? JSON.parse(text) : undefined;`,
    `    if (!res.ok) throw new ApiError(res.status, data);`,
    `    return schema.parse(data);`,
    `  }`,
  ];

  for (const op of ops) lines.push("", ...generateMethod(op));
  lines.push(`}`);
  return lines;
}

function generateMethod(op: Operation): string[] {
  const args: string[] = [];
  const hasParams = op.pathParams.length + op.queryParams.length > 0;
  const paramsSchema = hasParams
    ? `z.object({ ${[...op.pathParams, ...op.queryParams]
        .map((p) => `${JSON.stringify(p.name)}: ${schemaToZod(p.schema)}${p.required || p.in === "path" ? "" : ".optional()"}`)
        .join(", ")} })`
    : "";
  const paramsRequired = op.pathParams.length > 0 || op.queryParams.some((p) => p.required);
  const bodyZod = op.body ? schemaToZod(op.body) : "";

  if (hasParams) args.push(`params${paramsRequired ? "" : "?"}: z.input<typeof ${op.name}Params>`);
  if (op.body) args.push(`body${op.bodyRequired ? "" : "?"}: z.input<typeof ${op.name}Body>`);

  const responseZod = op.response ? schemaToZod(op.response) : "z.unknown()";
  const pathExpr =
    "`" + op.path.replace(/\{([^}]+)\}/g, (_, n) => `\${encodeURIComponent(String(p[${JSON.stringify(n)}]))}`) + "`";
  const query = op.queryParams.length
    ? `{ ${op.queryParams.map((q) => `${JSON.stringify(q.name)}: p[${JSON.stringify(q.name)}]`).join(", ")} }`
    : "undefined";

  const lines: string[] = [];
  if (hasParams) lines.push(`  static readonly ${op.name}Params = ${paramsSchema};`);
  if (op.body) lines.push(`  static readonly ${op.name}Body = ${indent(bodyZod)};`);
  lines.push(`  static readonly ${op.name}Response = ${indent(responseZod)};`);
  if (op.summary) lines.push(`  /** ${op.summary} */`);
  const typedArgs = args.map((a) => a.replace(/typeof (\w+)(Params|Body)/, "typeof ApiClient.$1$2"));
  lines.push(`  async ${op.name}(${typedArgs.join(", ")}): Promise<z.infer<typeof ApiClient.${op.name}Response>> {`);
  lines.push(
    hasParams
      ? `    const p = ApiClient.${op.name}Params.parse(params ?? {});`
      : `    const p = {} as Record<string, unknown>;`,
  );
  if (op.body) lines.push(`    const b = body === undefined ? undefined : ApiClient.${op.name}Body.parse(body);`);
  lines.push(
    `    return this.request(${JSON.stringify(op.method)}, ${pathExpr}, ApiClient.${op.name}Response, ${query}, ${op.body ? "b" : "undefined"});`,
  );
  lines.push(`  }`);
  return lines;
}

const indent = (s: string) => s.replace(/\n/g, "\n  ");
